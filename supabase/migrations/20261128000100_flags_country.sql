-- Country name for a phone number, or 'Unknown'. 10-digit numbers without + are Canada/US.
create or replace function public.phone_country(p text) returns text language sql stable set search_path = public as $$
  with n as (select case
      when p ~ '^\s*(\+|00)' then regexp_replace(regexp_replace(p, '^\s*00', ''), '\D', '', 'g')
      when regexp_replace(coalesce(p, ''), '\D', '', 'g') ~ '^\d{10}$' then '1' || regexp_replace(p, '\D', '', 'g')
      when regexp_replace(coalesce(p, ''), '\D', '', 'g') ~ '^1\d{10}$' then regexp_replace(p, '\D', '', 'g')
    end as d)
  select coalesce((select x.country from public.phone_prefixes x, n where n.d like x.prefix || '%' order by length(x.prefix) desc limit 1), 'Unknown')
$$;

-- Lead numbers without personal details, now also by country.
create or replace function public.call_stats(p_from date, p_to date) returns jsonb language plpgsql stable security definer set search_path = public as $$
declare r jsonb; tz text := 'America/Edmonton';
begin
  if not (public.has_perm('marketing.view') or public.has_perm('crm.view')) then raise exception 'Not allowed'; end if;
  with c as (
    select (occurred_at at time zone tz)::date as day, public.phone_country(from_number) as country, * from public.calls
    where direction = 'inbound' and (occurred_at at time zone tz)::date between p_from and p_to
  )
  select jsonb_build_object(
    'total', (select count(*) from c),
    'people', (select count(distinct coalesce(right(regexp_replace(from_number, '\D', '', 'g'), 10), id::text)) from c),
    'answered', (select count(*) from c where status = 'answered'),
    'missed', (select count(*) from c where status in ('missed', 'voicemail')),
    'by_category', coalesce((select jsonb_object_agg(category, n) from (select category, count(*) n from c group by 1) x), '{}'::jsonb),
    'by_source', coalesce((select jsonb_agg(x order by x.total desc) from (select source, count(*) total,
        count(*) filter (where category = 'potential') potential, count(*) filter (where category = 'booked') booked,
        count(*) filter (where category = 'paying') paying, count(*) filter (where category = 'just_asking') just_asking,
        count(*) filter (where status in ('missed', 'voicemail')) missed from c group by 1) x), '[]'::jsonb),
    'by_country', coalesce((select jsonb_agg(x order by x.total desc) from (select country, count(*) total,
        count(*) filter (where category in ('potential', 'booked', 'paying')) leads, count(*) filter (where category = 'paying') paying,
        count(*) filter (where status in ('missed', 'voicemail')) missed from c group by 1) x), '[]'::jsonb),
    'by_day', coalesce((select jsonb_agg(x order by x.day) from (select day, count(*) total,
        count(*) filter (where status = 'answered') answered, count(*) filter (where status in ('missed', 'voicemail')) missed from c group by 1) x), '[]'::jsonb),
    'by_hour', coalesce((select jsonb_agg(x order by x.h) from (select extract(hour from occurred_at at time zone tz)::int h, count(*) total,
        count(*) filter (where status = 'answered') answered, count(*) filter (where status in ('missed', 'voicemail')) missed from c group by 1) x), '[]'::jsonb)
  ) into r;
  return r;
end $$;

-- ── Flagged people ──
create table if not exists public.flags (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  phones      text[] not null default '{}',
  emails      text[] not null default '{}',
  reason      text not null default 'disappeared' check (reason in ('disappeared', 'no_show', 'not_paid', 'follow_up', 'do_not_serve', 'other')),
  notes       text,
  contact_id  uuid references public.contacts(id) on delete set null,
  remind_on   date,
  active      boolean not null default true,
  created_by  uuid default auth.uid() references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
alter table public.flags enable row level security;
create policy flags_select on public.flags for select to authenticated using (public.has_perm('crm.view'));
create policy flags_insert on public.flags for insert to authenticated with check (public.has_perm('crm.edit'));
create policy flags_update on public.flags for update to authenticated using (public.has_perm('crm.edit')) with check (public.has_perm('crm.edit'));
create policy flags_delete on public.flags for delete to authenticated using (public.has_perm('crm.edit'));
drop trigger if exists flags_touch on public.flags;
create trigger flags_touch before update on public.flags for each row execute function public.touch_updated_at();
